using System.Globalization;
using System.Text.Json.Nodes;

namespace EdgeGateway.Historian.Dashboards;

// Renders one device's Grafana dashboard from its catalog: a status row, then one row per register area with a
// panel per metric whose type follows the metric (numeric: time series; boolean: state timeline). Pure, so the
// same catalog always produces the same JSON and unchanged dashboards are not rewritten.
public static class DeviceDashboardBuilder
{
    public const string OverviewUid = "edge-history";
    private static readonly JsonObject Source = new() { ["type"] = "grafana-postgresql-datasource", ["uid"] = "history" };
    private const string ShortRange = "$__timeTo()::timestamptz - $__timeFrom()::timestamptz <= INTERVAL '1 day'";
    private const string LongRange = "$__timeTo()::timestamptz - $__timeFrom()::timestamptz > INTERVAL '1 day'";

    private sealed record Area(string Title, Func<CatalogMetric, bool> Includes);

    public static JsonObject Build(DeviceCatalog device)
    {
        var nodeFilter = $"node = {Literal(device.Node)}";
        var filter = $"{nodeFilter} AND device = {Literal(device.Device)}";
        var layout = new Layout();
        StatusRow(layout, nodeFilter, filter);

        // A metric the registry dropped stays charted (its history is still stored) in a row of its own,
        // unless the whole device was removed, in which case its rows simply show history.
        bool Current(CatalogMetric metric) => metric.InRegistry || !device.InRegistry;
        Area[] areas =
        [
            new("Input registers · measurements", metric => Current(metric) && metric.Register == "input"),
            new("Holding registers · setpoints", metric => Current(metric) && metric.Register == "holding"),
            new("Coils · outputs", metric => Current(metric) && metric.Register == "coil"),
            new("Discrete inputs", metric => Current(metric) && metric.Register == "discrete"),
            new("Other metrics", metric => Current(metric) && metric.Register is null or not ("input" or "holding" or "coil" or "discrete")),
            new("Removed metrics · history only", metric => !Current(metric))
        ];
        foreach (var area in areas)
        {
            var metrics = device.Metrics.Where(area.Includes).ToArray();
            if (metrics.Length == 0) continue;
            layout.Row($"{area.Title} ({metrics.Length})");
            foreach (var metric in metrics)
            {
                if (metric.IsBoolean) BooleanPanels(layout, filter, metric);
                else NumericPanels(layout, filter, metric);
            }
        }

        layout.Row("Data quality");
        layout.Add(Panel("table", "Latest bad or stale readings", 24, 7, Query("table", $"""
            SELECT time, coalesce(c.name, metric) AS metric, quality
            FROM readings LEFT JOIN metric_catalog c USING (node, device, metric)
            WHERE $__timeFilter(time) AND {filter} AND quality <> 'good'
            ORDER BY time DESC
            LIMIT 50
            """)));

        return new JsonObject
        {
            ["uid"] = device.Uid,
            ["title"] = $"{device.Device} · {device.Node}" + (device.InRegistry ? "" : " (removed)"),
            ["description"] = $"Generated by the historian for device {device.Device} on {device.Node}. Do not edit: it is rewritten when the device's metrics change.",
            ["tags"] = new JsonArray("device", "node:" + device.Node),
            ["timezone"] = "browser",
            ["editable"] = false,
            ["graphTooltip"] = 1,
            ["refresh"] = "5s",
            ["schemaVersion"] = 39,
            ["time"] = new JsonObject { ["from"] = "now-1h", ["to"] = "now" },
            ["links"] = new JsonArray(
                new JsonObject { ["title"] = "Fleet overview", ["type"] = "link", ["url"] = $"/d/{OverviewUid}", ["icon"] = "dashboard", ["keepTime"] = true },
                new JsonObject { ["title"] = "Devices", ["type"] = "dashboards", ["tags"] = new JsonArray("device"), ["asDropdown"] = true, ["keepTime"] = true }),
            ["templating"] = new JsonObject { ["list"] = new JsonArray() },
            ["panels"] = layout.Panels
        };
    }

    private static void StatusRow(Layout layout, string nodeFilter, string filter)
    {
        layout.Row("Status");
        // Births and deaths of this device, plus its gateway's deaths, which take every device offline.
        var online = Panel("state-timeline", "Online / offline", 24, 4, Query("time_series", $"""
            WITH events AS (
              SELECT time, kind, event_order FROM device_events WHERE {filter}
              UNION ALL
              SELECT time, kind, event_order FROM device_events WHERE {nodeFilter} AND kind = 'NDEATH'
            ), states AS (
              SELECT DISTINCT ON (time) time, CASE WHEN kind = 'DBIRTH' THEN 1 ELSE 0 END AS value
              FROM events WHERE time <= $__timeTo()
              ORDER BY time, event_order DESC
            )
            SELECT time, value AS "Online" FROM states
            UNION ALL
            SELECT $__timeTo(), value FROM (SELECT time, value FROM states ORDER BY time DESC LIMIT 1) latest
            WHERE time < $__timeTo()
            ORDER BY 1
            """), "Device births and deaths: DBIRTH = online; DDEATH, or the gateway's NDEATH = offline.");
        online["fieldConfig"] = Defaults(new JsonObject
        {
            ["custom"] = new JsonObject { ["fillOpacity"] = 80, ["lineWidth"] = 0, ["spanNulls"] = true },
            ["mappings"] = Mapping(("1", "Online", "green"), ("0", "Offline", "red")),
            ["color"] = new JsonObject { ["mode"] = "thresholds" }
        });
        online["options"] = new JsonObject { ["showValue"] = "never", ["mergeValues"] = true, ["rowHeight"] = 0.8, ["legend"] = new JsonObject { ["showLegend"] = false } };
        layout.Add(online);

        var last = Stat("Last reading", Query("table", $"""
            SELECT extract(epoch FROM max(time)) * 1000 AS "Last reading"
            FROM readings WHERE {filter} AND time > now() - INTERVAL '30 days'
            """));
        last["fieldConfig"] = Defaults(new JsonObject { ["unit"] = "dateTimeFromNow", ["noValue"] = "None in 30 days" });
        layout.Add(last);
        layout.Add(Stat("Readings in range", Query("table", $"""
            SELECT count(*) AS readings FROM readings WHERE $__timeFilter(time) AND {filter}
            """)));
        var bad = Stat("Bad or stale in range", Query("table", $"""
            SELECT count(*) AS "bad readings" FROM readings WHERE $__timeFilter(time) AND {filter} AND quality <> 'good'
            """));
        bad["fieldConfig"] = Defaults(new JsonObject { ["color"] = new JsonObject { ["mode"] = "thresholds" }, ["thresholds"] = Thresholds("green", ("red", 1)) });
        ((JsonObject)bad["options"]!)["colorMode"] = "background";
        layout.Add(bad);
        layout.Add(Stat("Replayed samples in range", Query("table", $"""
            SELECT count(DISTINCT (device_seq, time)) AS replayed FROM readings WHERE $__timeFilter(time) AND {filter} AND historical
            """), "Samples the gateway buffered while the broker was unreachable and sent afterwards."));
    }

    private static void NumericPanels(Layout layout, string filter, CatalogMetric metric)
    {
        var where = $"{filter} AND metric = {Literal(metric.Metric)}";
        // Raw readings up to a day; the 1-minute rollups beyond that.
        var series = Panel("timeseries", metric.Name, 18, 8, Query("time_series", $"""
            SELECT $__timeGroupAlias(time, $__interval), avg(value) AS value
            FROM readings
            WHERE $__timeFilter(time) AND {where} AND {ShortRange}
            GROUP BY 1
            UNION ALL
            SELECT $__timeGroupAlias(bucket, $__interval), sum(avg * samples) / nullif(sum(samples), 0)
            FROM readings_1m
            WHERE $__timeFilter(bucket) AND {where} AND {LongRange}
            GROUP BY 1
            ORDER BY 1
            """), Describe(metric));
        var custom = new JsonObject { ["lineWidth"] = 2, ["spanNulls"] = false, ["showPoints"] = "never", ["fillOpacity"] = 10 };
        // Setpoints change in steps; a sloped line between two settings would show values that never existed.
        if (metric.Register == "holding") custom["lineInterpolation"] = "stepAfter";
        series["fieldConfig"] = Defaults(Units(metric, new JsonObject { ["displayName"] = metric.Name, ["custom"] = custom }));
        series["options"] = new JsonObject
        {
            ["legend"] = new JsonObject { ["displayMode"] = "table", ["placement"] = "bottom", ["calcs"] = new JsonArray("min", "mean", "max", "lastNotNull") },
            ["tooltip"] = new JsonObject { ["mode"] = "single" }
        };
        layout.Add(series);

        var latest = Stat("Latest", Query("table", Latest(where)), "Most recent sample. Empty when it was bad or stale.", height: 8, width: 6);
        latest["fieldConfig"] = Defaults(Units(metric, new JsonObject { ["noValue"] = "No good value" }));
        ((JsonObject)latest["options"]!)["graphMode"] = "none";
        layout.Add(latest);
    }

    private static void BooleanPanels(Layout layout, string filter, CatalogMetric metric)
    {
        var where = $"{filter} AND metric = {Literal(metric.Metric)}";
        var states = Mapping(("1", "ON", "green"), ("0", "OFF", "text"));
        var timeline = Panel("state-timeline", metric.Name, 16, 5, Query("time_series", $"""
            SELECT time, value
            FROM readings
            WHERE $__timeFilter(time) AND {where} AND {ShortRange}
            UNION ALL
            SELECT bucket, round(avg)
            FROM readings_1m
            WHERE $__timeFilter(bucket) AND {where} AND {LongRange}
            ORDER BY 1
            """), Describe(metric));
        timeline["fieldConfig"] = Defaults(new JsonObject
        {
            ["displayName"] = metric.Name,
            ["custom"] = new JsonObject { ["fillOpacity"] = 80, ["lineWidth"] = 0, ["spanNulls"] = false },
            ["mappings"] = states,
            ["color"] = new JsonObject { ["mode"] = "thresholds" },
            ["thresholds"] = Thresholds("text", ("green", 1))
        });
        timeline["options"] = new JsonObject { ["showValue"] = "never", ["mergeValues"] = true, ["rowHeight"] = 0.8, ["legend"] = new JsonObject { ["showLegend"] = false } };
        layout.Add(timeline);

        var current = Stat("Now", Query("table", Latest(where)), "Most recent sample. Empty when it was bad or stale.", height: 5, width: 4);
        current["fieldConfig"] = Defaults(new JsonObject
        {
            ["mappings"] = Mapping(("1", "ON", "green"), ("0", "OFF", "text")),
            ["noValue"] = "No good value"
        });
        layout.Add(current);
        layout.Add(Stat("Changes in range", Query("table", $"""
            SELECT count(*) AS changes
            FROM (
              SELECT value, lag(value) OVER (ORDER BY time) AS previous
              FROM readings
              WHERE $__timeFilter(time) AND {where} AND value IS NOT NULL
            ) samples
            WHERE previous IS NOT NULL AND value <> previous
            """), "How many times the state switched between ON and OFF.", height: 5, width: 4));
    }

    private static string Latest(string where) => $"""
        SELECT CASE WHEN quality = 'good' THEN value END AS value
        FROM readings
        WHERE {where} AND time > now() - INTERVAL '30 days'
        ORDER BY time DESC
        LIMIT 1
        """;

    // "Holding register · int16 · scale 0.1 · °C"
    private static string Describe(CatalogMetric metric)
    {
        if (metric.Register is null) return $"{(metric.IsBoolean ? "Boolean" : "Numeric")} metric (no registry description).";
        var parts = new List<string> { metric.Register switch
        {
            "holding" => "Holding register", "input" => "Input register", "coil" => "Coil", "discrete" => "Discrete input",
            var other => other
        } };
        if (metric.DataType is { Length: > 0 } type) parts.Add(type);
        if (metric.Scale is { } scale && scale != 1) parts.Add("scale " + scale.ToString(CultureInfo.InvariantCulture));
        if (metric.Unit is { Length: > 0 } unit) parts.Add(unit);
        return string.Join(" · ", parts);
    }

    // Unit and decimals: integers keep 0 decimals unless the scale adds some; float32 shows 2.
    private static JsonObject Units(CatalogMetric metric, JsonObject defaults)
    {
        if (GrafanaUnit(metric.Unit) is { } unit) defaults["unit"] = unit;
        if (Decimals(metric) is { } decimals) defaults["decimals"] = decimals;
        return defaults;
    }

    public static int? Decimals(CatalogMetric metric)
    {
        var fromScale = 0;
        if (metric.Scale is { } scale && scale != 0)
            while (fromScale < 6 && Math.Abs(scale * Math.Pow(10, fromScale) - Math.Round(scale * Math.Pow(10, fromScale))) > 1e-9) fromScale++;
        return metric.DataType switch
        {
            "int16" or "uint16" or "int32" or "uint32" => fromScale,
            "float32" => Math.Max(2, fromScale),
            _ => null
        };
    }

    public static string? GrafanaUnit(string? unit) => unit?.Trim() switch
    {
        null or "" => null,
        "°C" or "C" or "degC" => "celsius",
        "°F" or "F" or "degF" => "fahrenheit",
        "K" => "kelvin",
        "%" => "percent",
        "V" => "volt", "mV" => "mvolt", "kV" => "kvolt",
        "A" => "amp", "mA" => "mamp",
        "W" => "watt", "kW" => "kwatt", "MW" => "megwatt",
        "Wh" => "watth", "kWh" => "kwatth",
        "Hz" => "hertz",
        "bar" => "pressurebar", "mbar" => "pressurembar", "Pa" => "pressurepa", "kPa" => "pressurekpa", "psi" => "pressurepsi",
        "rpm" => "rotrpm",
        "s" => "s", "ms" => "ms",
        "m" => "lengthm", "mm" => "lengthmm",
        "l" or "L" => "litre",
        var other => "suffix: " + other
    };

    public static string Literal(string text) => "'" + text.Replace("'", "''") + "'";

    private static JsonObject Panel(string type, string title, int width, int height, JsonObject target, string? description = null)
    {
        var panel = new JsonObject
        {
            ["type"] = type,
            ["title"] = title,
            ["datasource"] = Source.DeepClone(),
            ["gridPos"] = new JsonObject { ["w"] = width, ["h"] = height },
            ["targets"] = new JsonArray(target)
        };
        if (description is not null) panel["description"] = description;
        return panel;
    }

    private static JsonObject Stat(string title, JsonObject target, string? description = null, int height = 4, int width = 6)
    {
        var stat = Panel("stat", title, width, height, target, description);
        stat["options"] = new JsonObject
        {
            ["reduceOptions"] = new JsonObject { ["calcs"] = new JsonArray("lastNotNull"), ["fields"] = "", ["values"] = false },
            ["colorMode"] = "none",
            ["graphMode"] = "none",
            ["textMode"] = "value"
        };
        return stat;
    }

    private static JsonObject Query(string format, string sql) => new()
    {
        ["refId"] = "A",
        ["datasource"] = Source.DeepClone(),
        ["format"] = format,
        ["rawQuery"] = true,
        ["editorMode"] = "code",
        ["rawSql"] = sql.Replace("\r\n", "\n")
    };

    private static JsonObject Defaults(JsonObject defaults) => new() { ["defaults"] = defaults, ["overrides"] = new JsonArray() };

    private static JsonArray Mapping(params (string Value, string Text, string Color)[] values)
    {
        var options = new JsonObject();
        for (var index = 0; index < values.Length; index++)
            options[values[index].Value] = new JsonObject { ["text"] = values[index].Text, ["color"] = values[index].Color, ["index"] = index };
        return new JsonArray(new JsonObject { ["type"] = "value", ["options"] = options });
    }

    private static JsonObject Thresholds(string baseColor, params (string Color, double Value)[] steps)
    {
        var list = new JsonArray(new JsonObject { ["color"] = baseColor, ["value"] = null });
        foreach (var (color, value) in steps) list.Add(new JsonObject { ["color"] = color, ["value"] = value });
        return new JsonObject { ["mode"] = "absolute", ["steps"] = list };
    }

    // Places panels left to right in a 24-column grid, wrapping to a new line, and numbers them.
    private sealed class Layout
    {
        public JsonArray Panels { get; } = [];
        private int _x, _y, _lineHeight, _id;

        public void Row(string title)
        {
            NewLine();
            Panels.Add(new JsonObject
            {
                ["id"] = ++_id, ["type"] = "row", ["title"] = title, ["collapsed"] = false,
                ["gridPos"] = new JsonObject { ["x"] = 0, ["y"] = _y, ["w"] = 24, ["h"] = 1 },
                ["panels"] = new JsonArray()
            });
            _y++;
        }

        public void Add(JsonObject panel)
        {
            var grid = (JsonObject)panel["gridPos"]!;
            int width = (int)grid["w"]!, height = (int)grid["h"]!;
            if (_x + width > 24) NewLine();
            grid["x"] = _x;
            grid["y"] = _y;
            panel["id"] = ++_id;
            _x += width;
            _lineHeight = Math.Max(_lineHeight, height);
            Panels.Add(panel);
        }

        private void NewLine()
        {
            _y += _lineHeight;
            _x = 0;
            _lineHeight = 0;
        }
    }
}
